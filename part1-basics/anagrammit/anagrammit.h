#ifndef ANAGRAMMIT_H
#define ANAGRAMMIT_H

/*
Examines whether the parameter strings mj1 and mj2 are anagrams
(they contain exactly the same characters, but possibly in a different order).

Returns 1 if the strings are anagrams and otherwise 0.
The function must not change either of the parameter strings.
*/
int anagrammeja(char mj1[], char mj2[]);

#endif /* ANAGRAMMIT_H */